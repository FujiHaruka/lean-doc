/** Real docstrings, chosen for how much of the map they reach. */
const seen = new Set<string>();
const realAll: { what: string; depth: number; md: string; module: string }[] = [];
for (const mod of irModules) {
  const depth = (mod.module as string).split(".").length - 1;
  const add = (what: string, md: unknown) => {
    if (typeof md !== "string" || seen.has(md)) return;
    seen.add(md);
    realAll.push({ what, depth, md, module: mod.module });
  };
  for (const [i, doc] of mod.moduleDocs.entries()) add(`${mod.module} module doc ${i}`, doc.text);
  for (const decl of mod.declarations) {
    add(`${decl.name}`, decl.doc);
    for (const member of decl.members ?? []) add(`${decl.name}.${member.name}`, member.doc);
  }
}

/** `getRoot`: what `depthToRoot` produces. */
const rootOf = (depth: number) => "../".repeat(depth) + "./";

/**
 * The prototype's answer in a given world. Used twice: to pick the cases that
 * resolve something (so that the corpus is not mostly inert text), and, after
 * the oracle has run, to record where the prototype and doc-gen4 part company.
 *
 * `moduleDeclNames` is empty because doc-gen4's matching branch is disabled
 * here (`currentName := none`); anything else would compare two different
 * things.
 */
function renderPrototype(c: { depth: number; md: string; world: World }): string {
  prototype.known.clear();
  prototype.linkIndex.clear();
  for (const [n, m] of Object.entries(c.world.names)) prototype.known.set(n, m);
  return prototype.renderDocString(c.md, {
    root: rootOf(c.depth),
    moduleDeclNames: [],
    knownModules: new Set(c.world.modules),
  });
}

const countAnchors = (html: string) => (html.match(/<a href="/g) ?? []).length;

const scored = realAll
  .filter((c) => c.md.length <= COMPACT_CHARS)
  .map((c) => ({ ...c, world: worldFor(c.md) }))
  .map((c) => ({ ...c, anchors: countAnchors(renderPrototype(c)) }))
  .filter((c) => c.anchors > 0)
  .sort((a, b) => b.anchors - a.anchors);

// A spread over the ranking rather than the top of it, so the sample is not all
// one shape of docstring.
const picked: typeof scored = [];
const stride = Math.max(1, Math.floor(scored.length / REAL_CASES));
for (let i = 0; i < scored.length && picked.length < REAL_CASES; i += stride) picked.push(scored[i]);

