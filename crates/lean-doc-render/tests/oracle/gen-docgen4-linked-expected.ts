#!/usr/bin/env -S deno run --allow-read --allow-write --allow-run --allow-env
// gen-docgen4-linked-expected.ts -- produce the expected HTML for
// `tests/docgen4_linked.rs` by running *doc-gen4 itself* with a name map that
// is not empty.
//
// WHY THIS FILE EXISTS
// --------------------
// The primary oracle for autolink resolution is the frozen prototype
// (`gen-autolink-expected.ts`): plan §5 says so, because `render.ts`'s
// `nameToLink` is the function that scores 439/439 and doc-gen4's `nameToLink?`
// is a *different* function. But "the prototype is the target" is not the same
// as "the prototype is always right", and M1-c's earlier doc-gen4 comparison ran
// with every lookup missing -- so nothing had ever asked doc-gen4 what a
// *resolved* docstring looks like.
//
// This script asks. It fills `AnalyzerResult.name2ModIdx` and `.moduleNames`,
// which is all `nameToLink?`'s first three branches read, and compares. It
// found one real disagreement on the first run: the prototype auto-links a code
// span inside an `<a>` and doc-gen4 does not (`inLink`, `DocString.lean:264`
// vs `render.ts:1622`). No docstring of the target package reaches it 【実測:
// 0 of 4,858】, but the port follows doc-gen4, so the expectation has to come
// from doc-gen4.
//
// THE AGREEMENT ZONE
// ------------------
// The two specifications genuinely differ in three places, and this script
// keeps all three out of the corpus rather than hiding them:
//
//   * private names -- `isPrivateName` (mangling) vs a `_private.` prefix test;
//   * auto-generated eliminators -- doc-gen4 links `Foo.rec` to `Foo`;
//   * the "similar name in this module" branch -- doc-gen4 needs `moduleInfo`,
//     which cannot be built here, so `currentName := none` disables it and the
//     Rust side is rendered with an empty declaration list to match.
//
// Names that would need `Name.toString` to escape them (guillemets) are also
// left out: `declNameToLink` re-prints the `Name`, the prototype echoes the
// string it was given, and the two are only equal when the name round-trips.
//
// npm/node are broken in this environment; this must run under deno, and the
// oracle needs the measurement target (that is where doc-gen4 is built).
//
// usage:
//   deno run --allow-read --allow-write --allow-run --allow-env \
//     crates/lean-doc-render/tests/oracle/gen-docgen4-linked-expected.ts
//   ... --check                     fail if the committed file is stale
//   ... --target DIR --ir DIR --link-index FILE

