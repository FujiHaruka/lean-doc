{
  const text = await Deno.readTextFile(linkIndexPath);
  let module = "";
  let pos = 0;
  const n = text.length;
  while (pos < n) {
    let nl = text.indexOf("\n", pos);
    if (nl < 0) nl = n;
    const c = text.charCodeAt(pos);
    if (c === 9) fullLinkIndex.set(text.slice(pos + 1, nl), module);
    else if (c === 64) fullKnownModules.add(text.slice(pos + 1, nl));
    else if (c === 35) { /* format marker */ }
    else if (nl > pos) module = text.slice(pos, nl);
    pos = nl + 1;
  }
}

// ------------------------------------------------------------- agreement zone

/**
 * Whether a name may go into a world at all.
 *
 * Everything rejected here is a place the two specifications are known to
 * differ, so putting it in would produce a difference that says nothing.
 */
function admissible(name: string): boolean {
  if (!prototype.isNameLit(name)) return false;
  if (name.includes("«") || name.includes("»")) return false;
  if (name.startsWith("_private.")) return false;
  const last = name.slice(name.lastIndexOf(".") + 1);
  return !AUTO_SUFFIXES.has(last);
}

/** Words a docstring could plausibly look up, over-approximated from its text. */
function tokensOf(md: string): Set<string> {
  const out = new Set<string>();
  for (const raw of md.split(/[\p{Z}\p{C}]/u)) {
    const trimmed = raw.replace(/^[`*_[\](){}<>"'.,;:!?]+/, "").replace(
      /[`*_[\](){}<>"',;:]+$/,
      "",
    );
    for (const piece of [raw, trimmed]) {
      if (piece === "") continue;
      out.add(piece);
      const dot = piece.lastIndexOf(".");
      if (dot >= 0) out.add(piece.slice(dot + 1));
    }
  }
  return out;
}

type World = { modules: string[]; names: Record<string, string> };

/** The part of the real maps a docstring can reach, inside the agreement zone. */
function worldFor(md: string): World {
  const names: Record<string, string> = {};
  const modules = new Set<string>();
  for (const token of [...tokensOf(md)].sort()) {
    if (!admissible(token)) continue;
    const owner = fullKnown.get(token) ?? fullLinkIndex.get(token);
    if (owner !== undefined && admissible(owner)) {
      names[token] = owner;
      modules.add(owner);
    }
    if (fullKnownModules.has(token)) modules.add(token);
  }
  return { modules: [...modules].sort(), names };
}

