/// The result of `merge --verify A --against B`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct VerifyReport {
    /// Everything the prototype prints, in order, one line per entry.
    pub lines: Vec<String>,
    /// Problems found. Zero is exit 0.
    pub problems: usize,
    /// Module files that were byte for byte the same.
    pub module_files_identical: usize,
    pub modules_in_a: usize,
    pub dependency_entries_in_a: usize,
    pub dependency_entries_in_b: usize,
    pub dependency_mismatches: usize,
}

impl VerifyReport {
    /// The text `merge --verify` prints, which is the whole of its answer.
    #[must_use]
    pub fn to_text(&self) -> String {
        self.lines
            .iter()
            .map(|line| format!("{line}\n"))
            .collect::<String>()
    }
}

/// Compares two IR trees: module files byte for byte, index entries field by
/// field, dependency slices **as name -> module maps**.
///
/// The last of those is the prototype's own note, and it is now weaker than it
/// has to be: it says the slices' key order "comes out of a Lean HashMap and is
/// not reproducible outside Lean". It is (see the module heading), and
/// `tests/merge.rs` compares those files byte for byte. This comparison is left
/// on the mapping anyway, because it is what tells a *pipeline* that two trees
/// mean the same thing — and it is the only check that survives a future
/// extractor that emits them in another order.
pub fn verify(a: &Path, b: &Path) -> Result<VerifyReport, Error> {
    let mut lines: Vec<String> = Vec::new();
    let a_index_path = a.join("index.json");
    let b_index_path = b.join("index.json");
    let index_a: JsonObject = read_json(&a_index_path)?;
    let index_b: JsonObject = read_json(&b_index_path)?;
    let mut problems = 0usize;

    let map_a = module_map(&index_a, &a_index_path)?;
    let map_b = module_map(&index_b, &b_index_path)?;
    if map_a.len() != map_b.len() {
        lines.push(format!(
            "FAIL module count {} vs {}",
            map_a.len(),
            map_b.len()
        ));
        problems += 1;
    }
    let mut same = 0usize;
    for (name, entry_a) in &map_a {
        let Some(entry_b) = map_b
            .iter()
            .find(|(other, _)| other == name)
            .map(|(_, e)| e)
        else {
            lines.push(format!("FAIL missing in B: {name}"));
            problems += 1;
            continue;
        };
        for key in ["file", "bytes", "declarations", "contentHash"] {
            if entry_a.raw.get(key) != entry_b.raw.get(key) {
                lines.push(format!(
                    "FAIL index.{key} {name}: {} vs {}",
                    js_display(entry_a.raw.get(key)),
                    js_display(entry_b.raw.get(key)),
                ));
                problems += 1;
            }
        }
        let bytes_a = read(&a.join(&entry_a.file))?;
        let bytes_b = read(&b.join(&entry_b.file))?;
        if bytes_a == bytes_b {
            same += 1;
        } else {
            lines.push(format!("FAIL bytes differ: {name}"));
            problems += 1;
        }
    }
    lines.push(format!(
        "module files byte-identical: {same}/{}",
        map_a.len()
    ));

    // Dependency slices, compared as mappings.
    let dep_a = dep_mapping(a, &index_a, &a_index_path)?;
    let dep_b = dep_mapping(b, &index_b, &b_index_path)?;
    let lookup_b: HashMap<&str, &str> = dep_b
        .iter()
        .map(|(name, module)| (name.as_str(), module.as_str()))
        .collect();
    let lookup_a: HashSet<&str> = dep_a.iter().map(|(name, _)| name.as_str()).collect();
    let mut dep_bad = 0usize;
    for (name, module) in &dep_a {
        if lookup_b.get(name.as_str()).copied() != Some(module.as_str()) {
            if dep_bad < VERIFY_DEP_FAILURES {
                lines.push(format!(
                    "FAIL dep {name}: {module} vs {}",
                    lookup_b
                        .get(name.as_str())
                        .map_or("undefined", |found| *found)
                ));
            }
            dep_bad += 1;
        }
    }
    for (name, _) in &dep_b {
        if !lookup_a.contains(name.as_str()) {
            if dep_bad < VERIFY_DEP_FAILURES {
                lines.push(format!("FAIL dep only in B: {name}"));
            }
            dep_bad += 1;
        }
    }
    lines.push(format!(
        "dependency map entries: {} vs {}, mismatches {dep_bad}",
        dep_a.len(),
        dep_b.len()
    ));
    problems += dep_bad;
    lines.push(if problems == 0 {
        "VERIFY OK".to_owned()
    } else {
        format!("VERIFY FAILED ({problems} problems)")
    });

    Ok(VerifyReport {
        lines,
        problems,
        module_files_identical: same,
        modules_in_a: map_a.len(),
        dependency_entries_in_a: dep_a.len(),
        dependency_entries_in_b: dep_b.len(),
        dependency_mismatches: dep_bad,
    })
}

/// How many differing dependency names `verify` names before it only counts.
const VERIFY_DEP_FAILURES: usize = 10;

/// `new Map(index.modules.map(e => [e.module, e]))`: a repeated module keeps its
/// first position and takes its last value.
fn module_map(index: &JsonObject, path: &Path) -> Result<Vec<(String, IndexEntry)>, Error> {
    let mut out: Vec<(String, IndexEntry)> = Vec::new();
    for entry in index_entries(index, path)? {
        match out.iter_mut().find(|(name, _)| *name == entry.module) {
            Some(slot) => slot.1 = entry,
            None => out.push((entry.module.clone(), entry)),
        }
    }
    Ok(out)
}

/// Every dependency slice of a tree, flattened to `name -> module` in file
/// order — `idx.dependencyMaps ?? []`, so a tree with no such key is empty
/// rather than a failure.
fn dep_mapping(
    root: &Path,
    index: &JsonObject,
    path: &Path,
) -> Result<Vec<(String, String)>, Error> {
    let mut out: Vec<(String, String)> = Vec::new();
    let entries = match index.get("dependencyMaps") {
        None | Some(Value::Null) => Vec::new(),
        Some(Value::Array(entries)) => entries.clone(),
        Some(_) => {
            return Err(Error::IndexShape {
                path: path.to_owned(),
                message: "dependencyMaps is not an array".to_owned(),
            });
        }
    };
    for entry in entries {
        let Some(Value::String(file)) = entry.get("file") else {
            return Err(Error::IndexShape {
                path: path.to_owned(),
                message: "a dependencyMaps entry has no string `file`".to_owned(),
            });
        };
        let slice_path = root.join(file);
        let slice: JsonObject = read_json(&slice_path)?;
        let Some(Value::Object(declarations)) = slice.get("declarations") else {
            return Err(Error::IndexShape {
                path: slice_path,
                message: "declarations is not an object".to_owned(),
            });
        };
        for (name, module) in declarations {
            let module = match module {
                Value::String(module) => module.clone(),
                other => other.to_string(),
            };
            match out.iter_mut().find(|(other, _)| other == name) {
                Some(slot) => slot.1 = module,
                None => out.push((name.clone(), module)),
            }
        }
    }
    Ok(out)
}

/// One `index.json` module entry: the two fields this stage reads, plus the
/// object itself.
///
/// The **raw object is what goes back out**, key order and unknown keys
/// included: the merged index carries the extractor's entries verbatim, so a
/// typed struct here would quietly rewrite them into this crate's field order.
#[derive(Clone, Debug, PartialEq, Eq)]
struct IndexEntry {
    module: String,
    file: String,
    raw: Value,
}

/// `index.modules`, refused rather than guessed at when it is not an array of
/// objects each carrying `module` and `file` as strings.
///
/// The prototype would read `undefined` out of a malformed entry and write a
/// file called `undefined`; no extraction produces that, so it is a refusal.
fn index_entries(index: &JsonObject, path: &Path) -> Result<Vec<IndexEntry>, Error> {
    let shape = |message: &str| Error::IndexShape {
        path: path.to_owned(),
        message: message.to_owned(),
    };
    let Some(Value::Array(modules)) = index.get("modules") else {
        return Err(shape("modules is not an array"));
    };
    modules
        .iter()
        .map(|entry| {
            let string = |key: &str| match entry.get(key) {
                Some(Value::String(text)) => Ok(text.clone()),
                _ => Err(shape(&format!("an index entry has no string `{key}`"))),
            };
            Ok(IndexEntry {
                module: string("module")?,
                file: string("file")?,
                raw: entry.clone(),
            })
        })
        .collect()
}

/// `` `${value}` `` — how a template literal prints one of the four index
/// fields. A key that is not there prints `undefined`.
fn js_display(value: Option<&Value>) -> String {
    match value {
        None => "undefined".to_owned(),
        Some(Value::String(text)) => text.clone(),
        Some(other) => other.to_string(),
    }
}

fn read_json<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T, Error> {
    let text = fs::read_to_string(path).map_err(|source| Error::Io {
        path: path.to_owned(),
        source,
    })?;
    serde_json::from_str(&text).map_err(|source| Error::Json {
        path: path.to_owned(),
        source,
    })
}

fn read(path: &Path) -> Result<Vec<u8>, Error> {
    fs::read(path).map_err(|source| Error::Io {
        path: path.to_owned(),
        source,
    })
}

fn copy(from: &Path, to: &Path) -> Result<(), Error> {
    fs::copy(from, to).map(|_| ()).map_err(|source| Error::Io {
        path: from.to_owned(),
        source,
    })
}
