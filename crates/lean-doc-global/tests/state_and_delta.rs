/// A declaration with every schema-4 key `lean_doc_ir` requires — the same
/// shape the (now frozen) `tests/oracle/gen-global-expected.ts` wrote.
fn decl(name: &str, kind: &str, doc: Option<&str>, type_code: Value) -> Value {
    json!({
        "name": name, "kind": kind, "modifiers": [], "binders": [], "implicits": [],
        "binderCode": [], "type": "Prop", "typeCode": type_code, "line": 1, "col": 0,
        "endLine": 1, "endCol": 1, "index": 0, "members": [], "doc": doc,
        "equations": [], "equationCode": [], "refs": [],
    })
}

/// One module of a synthetic IR: name, imports, declarations, and the hash the
/// index will carry for it.
struct Synthetic {
    module: &'static str,
    hash: &'static str,
    imports: Vec<&'static str>,
    decls: Vec<Value>,
}

fn write_synthetic(root: &Path, modules: &[Synthetic], deps: &[(&str, Value)]) {
    let mut entries = Vec::new();
    let mut declarations = 0usize;
    for module in modules {
        let file = format!("modules/{}.json", module.module);
        let body = serde_json::to_string(&json!({
            "schemaVersion": 4,
            "module": module.module,
            "imports": module.imports,
            "moduleDocs": [],
            "tactics": [],
            "declarations": module.decls,
        }))
        .expect("serialises");
        let path = root.join(&file);
        fs::create_dir_all(path.parent().expect("a parent")).expect("writable");
        fs::write(&path, &body).expect("writable");
        declarations += module.decls.len();
        entries.push(json!({
            "bytes": body.len(),
            "contentHash": module.hash,
            "declarations": module.decls.len(),
            "file": file,
            "module": module.module,
        }));
    }
    let mut dep_entries = Vec::new();
    for (package, map) in deps {
        let file = format!("deps/{package}.json");
        let body = serde_json::to_string(&json!({
            "schemaVersion": 4, "package": package, "declarations": map,
        }))
        .expect("serialises");
        let path = root.join(&file);
        fs::create_dir_all(path.parent().expect("a parent")).expect("writable");
        fs::write(&path, &body).expect("writable");
        dep_entries.push(json!({
            "bytes": body.len(),
            "entries": map.as_object().expect("a map").len(),
            "file": file,
            "package": package,
        }));
    }
    write_json(
        &root.join("index.json"),
        &json!({
            "declarationCount": declarations,
            "dependencyMaps": dep_entries,
            "generator": "tests/state_and_delta.rs",
            "hashAlgorithm": "lean-string-hash-64/hex16",
            "leanVersion": "4.31.0",
            "moduleCount": modules.len(),
            "modules": entries,
            "schemaVersion": 4,
        }),
    );
}

/// U+1D49C MATHEMATICAL SCRIPT CAPITAL A: a surrogate pair, so it sorts *below*
/// every BMP name in UTF-16 and above them by code point (plan §7, U1). No name
/// of the target package is above the BMP【実測】, so nothing derived from the
/// corpus can tell the affected set's sort order from a UTF-8 one.
const ASTRAL: &str = "\u{1D49C}";

/// U+FB00 LATIN SMALL LIGATURE FF: the other half of U1.
///
/// [`ASTRAL`] alone proves nothing about the sort — its first UTF-16 code unit
/// is 0xD835, which is above every ASCII letter in *both* orders, so a UTF-8
/// sort puts it in the same place. It is only against a BMP character above the
/// surrogate range that the two orders invert: `𝒜` sorts **before** `ﬀ` in
/// UTF-16 and after it by code point. Every affected-set assertion below needs
/// both.
const LIGATURE: &str = "\u{FB00}";

/// The package the seven synthetic states start from.
