fn delta_fixture() -> DeltaExpected {
    serde_json::from_str(include_str!("data/delta-expected.json"))
        .expect("tests/data/delta-expected.json is valid")
}

/// The mutation was chosen by the generator to make the scan mean something:
/// three names, one of each kind, all of them mentioned by real docstrings.
#[test]
fn the_delta_fixture_is_a_real_delta() {
    let e = delta_fixture();
    assert!(
        e.changed_names > 0,
        "a delta with nothing changed proves nothing"
    );
    assert!(
        e.affected > 0,
        "a delta that affects nothing proves nothing"
    );
    assert_eq!(e.changed_sample.len(), e.changed_names.min(20));
    assert_eq!(e.affected, e.affected_modules.len());
    assert_eq!(e.witnesses.len(), 20.min(e.affected));
    assert!(
        e.affected > 20,
        "the corpus delta has to exceed the witness cap for the cap to be exercised"
    );
    assert_eq!(e.unchanged_print_set_bytes, 0);
    assert_ne!(e.mutation.moved_name, e.mutation.dropped_name);
}

