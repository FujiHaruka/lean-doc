// -------------------------------------------------------- the curated cases

/// The four ways a state file can be foreign that the seven states do not
/// produce: unparseable, and each of the three version keys other than
/// `derivation`.
///
/// Every one of them must load as an empty cache — silently, and with every
/// module read again.
fn curated_state_branches() -> BTreeSet<&'static str> {
    let trees = TempDir::new("foreign-states");
    let base = trees.path.join("ir");
    synthetic_base(&base);
    let modules = IrTree::open(&base).expect("opens").index().modules.len();

    let mut covered = BTreeSet::new();
    for (what, damage) in [
        ("unparseable", Damage::Corrupt("{\"stateVersion\": ")),
        ("not JSON at all", Damage::Corrupt("nonsense")),
        ("an empty file", Damage::Corrupt("")),
        ("a JSON array", Damage::Corrupt("[]")),
        ("a newer format", Damage::Key("stateVersion", json!(99))),
        ("another schema", Damage::Key("schemaVersion", json!(3))),
        (
            "another extractor",
            Damage::Key("generator", json!("some other extractor")),
        ),
    ] {
        let mut sequence = Sequence::new(what);
        let warm = sequence.step("warm", &base);
        assert_eq!(warm.misses, modules);
        let hot = sequence.step("hot", &base);
        assert_eq!(hot.hits, modules, "{what}: the cache did not warm up");
        match damage {
            Damage::Corrupt(body) => sequence.corrupt(body),
            Damage::Key(key, value) => sequence.tamper(key, value),
        }
        let cold = sequence.step("damaged", &base);
        assert_eq!(
            (cold.hits, cold.misses),
            (0, modules),
            "{what}: a state that is not this run's was used as a cache"
        );
        covered.extend(sequence.covered);
    }
    covered
}

enum Damage {
    Corrupt(&'static str),
    Key(&'static str, Value),
}

/// U+088F ARABIC HALF MADDA OVER MADDA: **a separator for V8 and not for
/// UnicodeBasic**, the first of the 4,803 code points the two tables disagree
/// about 【実測 2026-08-12】. Nothing in the target package contains it, or any
/// of the other 4,802.
const V8_ONLY_SEPARATOR: char = '\u{088F}';

/// V6: the tokeniser splits on the **union** of the prototype's separator set
/// and the renderer's, and the corpus reaches neither half of the disagreement.
///
/// The failure this rules out is silent. With the split narrowed to
/// UnicodeBasic's set — the renderer's, and the obvious "simplification" —
/// `` `Pkg.moved\u{088F}Tail` `` is one token, `Pkg.moved` is not among a
/// module's tokens, and the module is **missing from the affected set** when
/// `Pkg.moved` moves. Nothing downstream notices: the site builds and the page
/// keeps a link to the module the name used to live in.
fn curated_token_branches() -> BTreeSet<&'static str> {
    let trees = TempDir::new("curated-tokens");
    let ir = trees.path.join("ir");
    let split_doc = format!("`Pkg.moved{V8_ONLY_SEPARATOR}Tail`");
    write_synthetic(
        &ir,
        &[
            Synthetic {
                module: "Pkg.Alpha",
                hash: "1111111111111111",
                imports: vec![],
                decls: vec![decl("Pkg.moved", "def", None, json!([]))],
            },
            // The control: the same name in a code span with nothing unusual in
            // it, so that a delta that finds nothing at all is not mistaken for
            // the separator being handled.
            Synthetic {
                module: "Pkg.Plain",
                hash: "2222222222222222",
                imports: vec![],
                decls: vec![decl("Pkg.Plain.p", "def", Some("`Pkg.moved`."), json!([]))],
            },
            Synthetic {
                module: "Pkg.Split",
                hash: "3333333333333333",
                imports: vec![],
                decls: vec![decl("Pkg.Split.s", "def", Some(&split_doc), json!([]))],
            },
        ],
        &[],
    );

    let site = trees.path.join("site");
    build_global(&GlobalOptions::new(&ir, &site)).expect("builds");
    let mut before = name_map(&site);
    before.insert("Pkg.moved".to_owned(), "Somewhere.Else".to_owned());
    let (fired, delta) = run_delta(&trees, "separator", &ir, before, true, true);
    assert_eq!(delta.changed, ["Pkg.moved"]);
    assert_eq!(
        delta.affected,
        ["Pkg.Plain", "Pkg.Split"],
        "`Pkg.Split` mentions `Pkg.moved` before a code point V8 separates on and UnicodeBasic \
         does not; splitting on UnicodeBasic's set alone drops it from the affected set and \
         leaves its page linking a name that has moved"
    );
    assert_eq!(delta.witnesses[1].name, "Pkg.moved");
    // The same thing one level down, so that a failure above can be read
    // without guessing which half of the pipeline moved.
    assert_eq!(
        autolink_tokens(&split_doc),
        ["Pkg.moved", "moved", "Tail"],
        "the split is not the union of the two separator sets: U+{:04X} stayed inside a token",
        V8_ONLY_SEPARATOR as u32
    );
    assert!(
        fired.contains("tokenSeparatorV8Only"),
        "the curated IR does not actually contain a disputed code point"
    );
    fired
}

/// The delta's corners, over IRs small enough to say what the answer should be.
fn curated_delta_branches() -> BTreeSet<&'static str> {
    let trees = TempDir::new("curated-deltas");
    let mut covered = BTreeSet::new();

    // A package whose modules mention each other, in an index order that is not
    // the sorted order, and whose last two modules are the U1 pair: `Pkg.𝒜`
    // sorts before `Pkg.ﬀ` in UTF-16 and after it by code point, so the
    // affected set below is the only thing in this suite that can tell
    // `cmp_utf16` from `str::cmp`.
    let astral_module: &'static str = Box::leak(format!("Pkg.{ASTRAL}").into_boxed_str());
    let astral_decl: &'static str = Box::leak(format!("Pkg.{ASTRAL}.g").into_boxed_str());
    let ligature_module: &'static str = Box::leak(format!("Pkg.{LIGATURE}").into_boxed_str());
    let ligature_decl: &'static str = Box::leak(format!("Pkg.{LIGATURE}.h").into_boxed_str());
    let ir = trees.path.join("ir");
    write_synthetic(
        &ir,
        &[
            Synthetic {
                module: "Pkg.Zed",
                hash: "1111111111111111",
                imports: vec![],
                // `Pkg.aaa` sorts before `Pkg.moved` among this module's
                // tokens, so the witness is not the first token unless the scan
                // looks for the *matching* one.
                decls: vec![decl(
                    "Pkg.Zed.z",
                    "def",
                    Some("`Pkg.aaa` and `Pkg.moved`."),
                    json!([]),
                )],
            },
            Synthetic {
                module: "Pkg.Alpha",
                hash: "2222222222222222",
                imports: vec![],
                decls: vec![
                    decl("Pkg.aaa", "def", Some("`Pkg.moved`."), json!([])),
                    decl("Pkg.moved", "def", None, json!([])),
                ],
            },
            Synthetic {
                module: astral_module,
                hash: "3333333333333333",
                imports: vec![],
                decls: vec![decl(astral_decl, "def", Some("`Pkg.moved`."), json!([]))],
            },
            Synthetic {
                module: ligature_module,
                hash: "5555555555555555",
                imports: vec![],
                decls: vec![decl(ligature_decl, "def", Some("`Pkg.moved`."), json!([]))],
            },
            Synthetic {
                module: "Pkg.Quiet",
                hash: "4444444444444444",
                imports: vec![],
                decls: vec![decl("Pkg.Quiet.q", "def", Some("no names here"), json!([]))],
            },
        ],
        &[("Dep", json!({ "Dep.one": "Dep.Home" }))],
    );

    let site = trees.path.join("site");
    let after: BTreeMap<String, String> = {
        let work = GlobalOptions::new(&ir, &site);
        build_global(&work).expect("builds");
        name_map(&site)
    };

    // 1. Nothing changed: the scan is skipped and the print set is a file with
    //    no bytes.
    let (fired, delta) = run_delta(&trees, "unchanged", &ir, after.clone(), true, true);
    assert!(delta.changed.is_empty() && delta.affected.is_empty());
    covered.extend(fired);

    // 2. A change nothing mentions: the scan runs and finds nothing.
    let mut quiet = after.clone();
    quiet.insert("Unmentioned.name".to_owned(), "Elsewhere".to_owned());
    let (fired, delta) = run_delta(&trees, "unmentioned", &ir, quiet, true, true);
    assert_eq!(delta.changed, ["Unmentioned.name"]);
    assert!(delta.affected.is_empty(), "nothing mentions that name");
    covered.extend(fired);

    // 3. All three kinds of change at once, on names the modules do mention.
    //    The affected set is written out in full here because it is the one
    //    assertion in this crate that a UTF-8 sort fails: `Pkg.𝒜` **before**
    //    `Pkg.ﬀ` (plan §7, U1).
    let mut moved = after.clone();
    moved.insert("Pkg.moved".to_owned(), "Somewhere.Else".to_owned());
    moved.remove("Pkg.aaa");
    moved.insert("Dep.gone".to_owned(), "Dep.Home".to_owned());
    let (fired, delta) = run_delta(&trees, "moved", &ir, moved, true, true);
    assert_eq!(delta.changed, ["Dep.gone", "Pkg.aaa", "Pkg.moved"]);
    assert_eq!(
        delta.affected,
        [
            "Pkg.Alpha".to_owned(),
            "Pkg.Zed".to_owned(),
            format!("Pkg.{ASTRAL}"),
            format!("Pkg.{LIGATURE}"),
        ],
        "the affected set is not in UTF-16 code unit order"
    );
    // Scanned in index order, so the witness list is not the sorted one.
    assert_eq!(
        delta
            .witnesses
            .iter()
            .map(|w| w.module.as_str())
            .collect::<Vec<_>>(),
        [
            "Pkg.Zed",
            "Pkg.Alpha",
            &format!("Pkg.{ASTRAL}"),
            &format!("Pkg.{LIGATURE}")
        ],
    );
    // `Pkg.Zed`'s tokens are `Pkg.aaa`, `Pkg.moved`, `aaa`, `moved` in UTF-16
    // order; both of the first two changed, and the first one is the witness.
    assert_eq!(delta.witnesses[0].name, "Pkg.aaa");
    covered.extend(fired);

    // 4. The delta with neither output file: the counts still come back.
    let mut again = after.clone();
    again.insert("Pkg.moved".to_owned(), "Somewhere.Else".to_owned());
    let (fired, _) = run_delta(&trees, "no-outputs", &ir, again, false, false);
    covered.extend(fired);

    // 5. More than twenty changed names and more than twenty affected modules:
    //    the sample and the witness list are both capped, and the corpus's
    //    delta (3 changed names) reaches neither cap.
    let big = trees.path.join("ir-big");
    let mut modules = Vec::new();
    for i in 0..22 {
        let module: &'static str = Box::leak(format!("Pkg.M{i:02}").into_boxed_str());
        let name: &'static str = Box::leak(format!("Pkg.M{i:02}.d").into_boxed_str());
        modules.push(Synthetic {
            module,
            hash: "7777777777777777",
            imports: vec![],
            decls: vec![decl(name, "def", Some("`Everywhere.name`"), json!([]))],
        });
    }
    write_synthetic(&big, &modules, &[]);
    let big_site = trees.path.join("site-big");
    build_global(&GlobalOptions::new(&big, &big_site)).expect("builds");
    let mut before = name_map(&big_site);
    before.insert("Everywhere.name".to_owned(), "Gone.Away".to_owned());
    for i in 0..25 {
        before.insert(format!("Extra.n{i:02}"), "Gone.Away".to_owned());
    }
    let (fired, delta) = run_delta(&trees, "capped", &big, before, true, true);
    assert_eq!(delta.changed.len(), 26);
    assert_eq!(delta.affected.len(), 22);
    assert_eq!(
        delta.witnesses.len(),
        20,
        "the witness list is capped at 20"
    );
    covered.extend(fired);
    covered
}

/// Runs one delta over `ir` with `before` as the previous map.
fn run_delta(
    trees: &TempDir,
    what: &str,
    ir: &Path,
    before: BTreeMap<String, String>,
    print_set: bool,
    delta_json: bool,
) -> (BTreeSet<&'static str>, Delta) {
    let before_path = trees.path.join(format!("{what}-before.json"));
    fs::write(
        &before_path,
        serde_json::to_string(&before).expect("serialises"),
    )
    .expect("writable");
    let site = trees.path.join(format!("{what}-site"));
    let set = trees.path.join(format!("{what}-set.txt"));
    let json = trees.path.join(format!("{what}-delta.json"));

    let mut options = GlobalOptions::new(ir, &site);
    options.before = Some(&before_path);
    options.print_set = print_set.then_some(set.as_path());
    options.delta_json = delta_json.then_some(json.as_path());
    let summary = build_global(&options).unwrap_or_else(|e| panic!("{what}: {e}"));
    let tree = IrTree::open(ir).expect("opens");
    let facts = facts_for(&tree, &State::empty()).expect("reads").facts;

    // The delta as data has to agree with the two files it wrote.
    let delta = summary.delta.as_ref().expect("--before turns the delta on");
    if print_set {
        let body = fs::read_to_string(&set).expect("the print set was written");
        assert_eq!(body, delta.print_set(), "{what}");
    }
    if delta_json {
        let record: Value =
            serde_json::from_str(&fs::read_to_string(&json).expect("the summary was written"))
                .expect("the summary is JSON");
        assert_eq!(record["affected"], json!(delta.affected.len()), "{what}");
        assert_eq!(record["changedNames"], json!(delta.changed.len()), "{what}");
        assert_eq!(
            record["affectedModules"],
            json!(delta.affected),
            "{what}: the summary and the print set name different modules"
        );
    }
    // The same answer, computed straight from the two maps: the file-driven
    // path and the library path cannot drift apart.
    let after = name_map(&site);
    assert_eq!(*delta, Delta::compute(&before, &after, &facts), "{what}");

    let fired = observe(&Run {
        options: &options,
        index: tree.index(),
        state_before: None,
        state_after: None,
        summary: &summary,
        facts: &facts,
        before_map: Some(&before),
    });
    (fired, delta.clone())
}

