/// What one run of [`build_global`] was given and what came out of it.
struct Run<'a> {
    options: &'a GlobalOptions<'a>,
    index: &'a Index,
    /// The state file as it was **before** the run, if there was one.
    state_before: Option<String>,
    /// The state file as it is **after** the run.
    state_after: Option<String>,
    summary: &'a GlobalSummary,
    /// The facts of every module in index order, derived without a cache.
    facts: &'a [ModuleFacts],
    /// The two maps the delta compared, when it ran.
    before_map: Option<&'a BTreeMap<String, String>>,
}

/// Which branches a run reached.
///
/// Everything here is read off the run's inputs and outputs. Nothing re-derives
/// what the code under test decided — where a decision is needed (was this state
/// file usable? which modules should have hit?) it is made from the file on disk
/// and the index, and [`Sequence::step`] asserts that the code agreed.
fn observe(run: &Run<'_>) -> BTreeSet<&'static str> {
    let mut fired: BTreeSet<&'static str> = BTreeSet::new();
    let mut fire = |branch: &'static str| {
        assert!(
            BRANCHES.contains(&branch),
            "{branch} is not a counted branch"
        );
        fired.insert(branch);
    };

    match (run.options.state, &run.state_before) {
        (None, _) => fire("stateNotRequested"),
        (Some(_), None) => fire("stateFileMissing"),
        (Some(_), Some(text)) => match Verdict::of(text, run.index) {
            Verdict::Unparseable => fire("stateUnparseable"),
            Verdict::Foreign(which) => fire(which),
            Verdict::Usable(_) => fire("stateAccepted"),
        },
    }

    let cached = usable_cache(run);
    for entry in &run.index.modules {
        match cached.get(entry.module.as_str()) {
            None => fire("cacheMissNotCached"),
            Some(hash) if *hash == entry.content_hash => fire("cacheHit"),
            Some(_) => fire("cacheMissHashMoved"),
        }
    }
    if run.options.state.is_some() {
        fire("saveWritten");
        let live: BTreeSet<&str> = run
            .index
            .modules
            .iter()
            .map(|entry| entry.module.as_str())
            .collect();
        // Dropped, not merely stale: the entry was in the cache, its module is
        // not in the index any more, and the file that was just written does
        // not name it.
        let saved = saved_modules(run.state_after.as_deref());
        if cached
            .keys()
            .any(|module| !live.contains(module.as_str()) && !saved.contains(module.as_str()))
        {
            fire("saveDroppedEntry");
        }
    } else {
        fire("saveSkipped");
    }

    fire(if run.options.timings.is_some() {
        "timingsWritten"
    } else {
        "timingsOmitted"
    });

    // Read off the IR rather than off the facts: under the union no token can
    // contain a separator of either set, so the tokens cannot say whether the
    // split met one.
    if meets_a_v8_only_separator(run.options.ir) {
        fire("tokenSeparatorV8Only");
    }

    let (Some(delta), Some(before)) = (&run.summary.delta, run.before_map) else {
        fire("deltaOff");
        return fired;
    };
    fire("deltaOn");
    let after = name_map(run.options.out);
    for name in before.keys().chain(after.keys()) {
        match (before.get(name), after.get(name)) {
            (Some(a), Some(b)) if a != b => fire("changedValueDiffers"),
            (Some(_), None) => fire("changedOnlyInBefore"),
            (None, Some(_)) => fire("changedOnlyInAfter"),
            _ => {}
        }
    }
    if delta.changed.is_empty() {
        fire("changedEmpty");
    }
    if delta.changed.len() > 20 {
        fire("changedSampleTruncated");
    }
    // "The scan ran and found nothing", not "there was nothing to scan for":
    // the empty-change case is `changedEmpty`, and the two write the same file
    // by two different roads.
    if delta.affected.is_empty() {
        if !delta.changed.is_empty() {
            fire("affectedEmpty");
        }
    } else {
        fire("affectedNonEmpty");
    }
    if delta.affected.len() > 20 {
        fire("witnessLimitReached");
    }
    // The witness is the first *matching* token of the module's sorted token
    // list, which is only the first token when the changed name happens to sort
    // first.
    for witness in &delta.witnesses {
        let facts = run
            .facts
            .iter()
            .find(|facts| facts.module == witness.module)
            .expect("a witness names a module of this IR");
        if facts.tokens.first() != Some(&witness.name) {
            fire("witnessNotFirstToken");
        }
    }
    let in_index_order: Vec<&String> = run
        .facts
        .iter()
        .map(|facts| &facts.module)
        .filter(|module| delta.affected.contains(module))
        .collect();
    if in_index_order != delta.affected.iter().collect::<Vec<_>>() {
        fire("affectedSortReorders");
    }
    if delta
        .affected
        .iter()
        .any(|module| module.chars().any(|c| c as u32 > 0xFFFF))
    {
        fire("affectedAboveBmp");
    }
    match run.options.print_set {
        None => fire("printSetOmitted"),
        Some(path) => {
            let body = fs::read(path).expect("the print set was written");
            if delta.affected.is_empty() {
                assert_eq!(body, b"", "an empty affected set is a file with no bytes");
                fire("printSetEmptyFile");
            } else {
                fire("printSetNonEmpty");
            }
        }
    }
    fire(if run.options.delta_json.is_some() {
        "deltaJsonWritten"
    } else {
        "deltaJsonOmitted"
    });
    fired
}

/// Whether any code span in this IR's declaration docstrings holds a code point
/// **V8 splits on and UnicodeBasic does not** — the direction of the
/// disagreement that costs correctness (plan §8, V6, and
/// `lean_doc_global::is_token_separator`).
///
/// The other direction is not looked for because it is empty: no code point is a
/// separator for UnicodeBasic and not for V8 【実測 2026-08-12, asserted by
/// `facts::tests::the_two_separator_sets_disagree_the_way_v6_measured_them`】.
///
/// Memoised per path — every tree this suite mutates is written before the first
/// run over it, so the answer for a path does not change once it has been asked.
fn meets_a_v8_only_separator(ir: &Path) -> bool {
    static SEEN: OnceLock<Mutex<BTreeMap<PathBuf, bool>>> = OnceLock::new();
    let seen = SEEN.get_or_init(|| Mutex::new(BTreeMap::new()));
    if let Some(answer) = seen.lock().expect("the memo is not poisoned").get(ir) {
        return *answer;
    }
    let tree = IrTree::open(ir).expect("the IR opens");
    let found = tree.modules().any(|module| {
        let module = module.expect("the module reads");
        module.declarations.iter().any(|decl| {
            decl.doc.as_deref().is_some_and(|doc| {
                backtick_spans(doc)
                    .iter()
                    .any(|span| span.chars().any(is_v8_only_separator))
            })
        })
    });
    seen.lock()
        .expect("the memo is not poisoned")
        .insert(ir.to_owned(), found);
    found
}

fn is_v8_only_separator(c: char) -> bool {
    v8_gc::is_z_c(c) && !lean_doc_md::gc::is_z_c(c)
}

/// The inside of every `` `...` ``, as ``/`([^`\n]+)`/g`` finds them — the
/// test's own reading of the regex, so that the crate's is not both the thing
/// under test and the authority on what it saw.
fn backtick_spans(doc: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut rest = doc;
    while let Some(open) = rest.find('`') {
        let after = &rest[open + 1..];
        // A run that stops on anything but a closing backtick is not a match,
        // and the regex engine retries from one position past the opening one.
        match after.find(['`', '\n']) {
            Some(at) if at > 0 && after.as_bytes()[at] == b'`' => {
                out.push(&after[..at]);
                rest = &after[at + 1..];
            }
            _ => rest = after,
        }
    }
    out
}

/// What a state file on disk is worth to a run over `index` — the test's own
/// reading of the four version keys, so that the code's reading has something to
/// disagree with.
enum Verdict {
    Unparseable,
    /// Which of the four keys disagreed.
    Foreign(&'static str),
    /// module -> the `contentHash` the entry was built for.
    Usable(BTreeMap<String, String>),
}

impl Verdict {
    fn of(text: &str, index: &Index) -> Self {
        let Ok(value) = serde_json::from_str::<Value>(text) else {
            return Self::Unparseable;
        };
        let Some(object) = value.as_object() else {
            return Self::Unparseable;
        };
        if object.get("stateVersion").and_then(Value::as_u64) != Some(STATE_VERSION) {
            return match object.get("stateVersion") {
                Some(Value::Number(_)) => Self::Foreign("stateVersionMismatch"),
                _ => Self::Unparseable,
            };
        }
        match object.get("derivation").and_then(Value::as_str) {
            Some(STATE_DERIVATION) => {}
            Some(_) => return Self::Foreign("stateDerivationMismatch"),
            None => return Self::Unparseable,
        }
        match object.get("schemaVersion").and_then(Value::as_u64) {
            Some(version) if version == u64::from(index.schema_version) => {}
            Some(_) => return Self::Foreign("stateSchemaMismatch"),
            None => return Self::Unparseable,
        }
        match object.get("generator").and_then(Value::as_str) {
            Some(generator) if generator == index.generator => {}
            Some(_) => return Self::Foreign("stateGeneratorMismatch"),
            None => return Self::Unparseable,
        }
        let modules = object.get("modules").and_then(Value::as_object);
        Self::Usable(
            modules
                .map(|modules| {
                    modules
                        .iter()
                        .filter_map(|(module, facts)| {
                            let hash = facts.get("contentHash")?.as_str()?;
                            Some((module.clone(), hash.to_owned()))
                        })
                        .collect()
                })
                .unwrap_or_default(),
        )
    }
}

/// The entries the run should have been able to hit, module -> hash.
fn usable_cache(run: &Run<'_>) -> BTreeMap<String, String> {
    match (run.options.state, &run.state_before) {
        (Some(_), Some(text)) => match Verdict::of(text, run.index) {
            Verdict::Usable(entries) => entries,
            _ => BTreeMap::new(),
        },
        _ => BTreeMap::new(),
    }
}

/// The modules a state file names, or none when there is no file.
fn saved_modules(state: Option<&str>) -> BTreeSet<String> {
    let Some(text) = state else {
        return BTreeSet::new();
    };
    serde_json::from_str::<Value>(text)
        .ok()
        .and_then(|value| Some(value.get("modules")?.as_object()?.keys().cloned().collect()))
        .unwrap_or_default()
}

fn name_map(site: &Path) -> BTreeMap<String, String> {
    let text = fs::read_to_string(site.join(NAME_MAP)).expect("name-map.json was written");
    serde_json::from_str(&text).expect("name-map.json is a flat string map")
}

// ------------------------------------------------------------- the sequence

/// One run of the seven states, carrying a cache from the first to the last.
struct Sequence {
    work: TempDir,
    state: PathBuf,
    /// The branches every step of this sequence reached, together.
    covered: BTreeSet<&'static str>,
    steps: usize,
}

/// What one state of the sequence proved.
struct Step {
    hits: usize,
    misses: usize,
}

impl Sequence {
    fn new(what: &str) -> Self {
        let work = TempDir::new(what);
        let state = work.path.join("state");
        Self {
            work,
            state,
            covered: BTreeSet::new(),
            steps: 0,
        }
    }

    /// `oracle.sh`'s `step`: build the same IR twice — from scratch, and with
    /// the cache carried in from the last state — and compare all six.
    fn step(&mut self, name: &str, ir: &Path) -> Step {
        self.steps += 1;
        let scratch = self.work.path.join(format!("{name}-scratch"));
        let cached = self.work.path.join(format!("{name}-cached"));
        let timings = self.work.path.join(format!("{name}-timings.json"));
        let _ = fs::remove_dir_all(&scratch);
        let _ = fs::remove_dir_all(&cached);

        let tree = IrTree::open(ir).expect("the IR opens");
        let facts = facts_for(&tree, &State::empty())
            .expect("the IR reads")
            .facts;

        // The from-scratch side: the program M2-a was judged on, unchanged.
        let scratch_options = GlobalOptions::new(ir, &scratch);
        let scratch_summary = build_global(&scratch_options).expect("the from-scratch build runs");
        assert_eq!(scratch_summary.cache_hits, 0, "{name}: no state, no hits");
        assert_eq!(scratch_summary.state_bytes, 0, "{name}: no state, no file");
        self.covered.extend(observe(&Run {
            options: &scratch_options,
            index: tree.index(),
            state_before: None,
            state_after: None,
            summary: &scratch_summary,
            facts: &facts,
            before_map: None,
        }));

        // The cached side, carrying whatever the last step left behind.
        let state_before = fs::read_to_string(self.state.join(STATE_FILE)).ok();
        let mut options = GlobalOptions::new(ir, &cached);
        options.state = Some(&self.state);
        options.timings = Some(&timings);
        let summary = build_global(&options).expect("the cached build runs");
        let state_after = fs::read_to_string(self.state.join(STATE_FILE)).ok();

        // What the state file on disk said should have hit, decided here rather
        // than taken from the code that decided it.
        let expected = usable_cache(&Run {
            options: &options,
            index: tree.index(),
            state_before: state_before.clone(),
            state_after: state_after.clone(),
            summary: &summary,
            facts: &facts,
            before_map: None,
        });
        let predicted = tree
            .index()
            .modules
            .iter()
            .filter(|entry| expected.get(&entry.module) == Some(&entry.content_hash))
            .count();
        assert_eq!(
            summary.cache_hits, predicted,
            "{name}: the cache hit on modules whose hash had moved, or missed on ones it had"
        );
        assert_eq!(
            summary.cache_hits + summary.cache_misses,
            tree.index().modules.len(),
            "{name}: every module is either read or reused"
        );

        // The oracle's own assertion: the two builds are the same files.
        for path in ARTIFACT_PATHS {
            let want = fs::read(scratch.join(path)).expect("the from-scratch artifact");
            let got = fs::read(cached.join(path)).expect("the cached artifact");
            assert!(
                want == got,
                "{name}: {path} differs between the from-scratch and the cached build at byte {} \
                 ({} B against {} B)",
                got.iter()
                    .zip(&want)
                    .position(|(a, b)| a != b)
                    .unwrap_or_else(|| want.len().min(got.len())),
                got.len(),
                want.len(),
            );
        }

        // The state file names exactly the modules the index does, in its order.
        let saved: Value = serde_json::from_str(
            state_after
                .as_deref()
                .expect("the cached build wrote a state"),
        )
        .expect("the state file is JSON");
        let saved_modules: Vec<&String> = saved["modules"]
            .as_object()
            .expect("the state has a module map")
            .keys()
            .collect();
        let index_modules: Vec<&String> = tree
            .index()
            .modules
            .iter()
            .map(|entry| &entry.module)
            .collect();
        assert_eq!(
            saved_modules, index_modules,
            "{name}: the saved state is not the index's modules in the index's order"
        );

        // The timings record: what `oracle.sh` reads the counts out of.
        let record: Value =
            serde_json::from_str(&fs::read_to_string(&timings).expect("the timings were written"))
                .expect("the timings are JSON");
        assert_eq!(record["cacheHits"], json!(summary.cache_hits), "{name}");
        assert_eq!(record["cacheMisses"], json!(summary.cache_misses), "{name}");
        assert_eq!(record["state"], json!("on"), "{name}");

        self.covered.extend(observe(&Run {
            options: &options,
            index: tree.index(),
            state_before,
            state_after,
            summary: &summary,
            facts: &facts,
            before_map: None,
        }));

        Step {
            hits: summary.cache_hits,
            misses: summary.cache_misses,
        }
    }

    /// Rewrites one key of the state file, the way `oracle.sh`'s seventh step
    /// does with `derivation`.
    fn tamper(&self, key: &str, value: Value) {
        let path = self.state.join(STATE_FILE);
        let mut state: Value =
            serde_json::from_str(&fs::read_to_string(&path).expect("there is a state to tamper"))
                .expect("the state is JSON");
        state[key] = value;
        fs::write(
            &path,
            serde_json::to_string(&state).expect("the state serialises"),
        )
        .expect("the state is writable");
    }

    fn corrupt(&self, body: &str) {
        fs::write(self.state.join(STATE_FILE), body).expect("the state is writable");
    }
}

/// The seven states, run over whatever IR `base` is, with `work` for the copies.
///
/// The mutations are synthetic and are **not** claimed to be what the extractor
/// would emit — `oracle.sh` says the same. They only have to be a valid IR whose
/// bytes and hash move together, which is the invariant the cache is keyed on.
fn seven_states(what: &str, base: &Path, trees: &TempDir) -> Sequence {
    let mut sequence = Sequence::new(what);
    let modules = IrTree::open(base)
        .expect("the base IR opens")
        .index()
        .modules
        .len();

    // 1. the unchanged tree with no state at all: the cache must not be needed
    //    for correctness, only for speed.
    let base_step = sequence.step("base", base);
    assert_eq!((base_step.hits, base_step.misses), (0, modules));

    // 2. the same tree again: every module is a hit and the bytes must not move.
    let rerun = sequence.step("rerun", base);
    assert_eq!((rerun.hits, rerun.misses), (modules, 0));

    // 3. one module's bytes change, and the hash moves with them.
    let modified_ir = trees.path.join("ir-mod");
    copy_ir(base, &modified_ir);
    mutate_modified(&modified_ir);
    let modified = sequence.step("modified", &modified_ir);
    assert_eq!((modified.hits, modified.misses), (modules - 1, 1));

    // 4. two modules disappear. The index is the authority on what exists, so
    //    the cache entries have to go with them.
    let removed_ir = trees.path.join("ir-del");
    copy_ir(&modified_ir, &removed_ir);
    let gone = mutate_removed(&removed_ir, 2);
    assert_eq!(gone.len(), 2);
    let removed = sequence.step("removed", &removed_ir);
    assert_eq!((removed.hits, removed.misses), (modules - 2, 0));

    // 5. a module appears, with declarations nothing has seen.
    let added_ir = trees.path.join("ir-add");
    copy_ir(&removed_ir, &added_ir);
    mutate_added(&added_ir);
    let added = sequence.step("added", &added_ir);
    assert_eq!((added.hits, added.misses), (modules - 2, 1));

    // 6. back to the original tree, with a state that has seen all of the
    //    above. A cache that only ever grows passes every step so far and fails
    //    this one: the module that was modified has its old hash back, the two
    //    that were deleted are not in the state any more, and the one that was
    //    added must not survive into the file.
    let restored = sequence.step("restored", base);
    assert_eq!((restored.hits, restored.misses), (modules - 3, 3));

    // 7. a state written by a different derivation is a guess, not a cache.
    sequence.tamper("derivation", json!("some older rule"));
    let stale = sequence.step("stale-state", base);
    assert_eq!(
        (stale.hits, stale.misses),
        (0, modules),
        "a state with a foreign derivation id was used as a cache"
    );
    sequence
}

// ------------------------------------------------------------- the IR states

fn read_json(path: &Path) -> Value {
    serde_json::from_str(&fs::read_to_string(path).unwrap_or_else(|e| panic!("{path:?}: {e}")))
        .unwrap_or_else(|e| panic!("{path:?}: {e}"))
}

fn write_json(path: &Path, value: &Value) {
    fs::create_dir_all(path.parent().expect("a file has a parent")).expect("writable");
    fs::write(path, serde_json::to_string(value).expect("serialises")).expect("writable");
}

/// A copy of an IR tree that can be mutated without touching the original —
/// which for the real corpus is a fixture this suite must not write to.
fn copy_ir(from: &Path, to: &Path) {
    let _ = fs::remove_dir_all(to);
    fs::create_dir_all(to).expect("writable");
    let index = read_json(&from.join("index.json"));
    fs::write(
        to.join("index.json"),
        fs::read(from.join("index.json")).expect("readable"),
    )
    .expect("writable");
    let files = index["modules"]
        .as_array()
        .expect("modules")
        .iter()
        .chain(index["dependencyMaps"].as_array().into_iter().flatten())
        .map(|entry| entry["file"].as_str().expect("a file path").to_owned());
    for file in files {
        let target = to.join(&file);
        fs::create_dir_all(target.parent().expect("a file has a parent")).expect("writable");
        fs::copy(from.join(&file), target).expect("copyable");
    }
}

/// The index entries sorted the way `oracle.sh` sorts them: most declarations
/// first, ties in index order (Python's sort is stable, and so is this one).
fn by_declarations(index: &Value) -> Vec<usize> {
    let modules = index["modules"].as_array().expect("modules");
    let mut order: Vec<usize> = (0..modules.len()).collect();
    order.sort_by_key(|i| std::cmp::Reverse(modules[*i]["declarations"].as_u64().unwrap_or(0)));
    order
}

/// State 3: a declaration is renamed and the module's hash moves with it.
fn mutate_modified(ir: &Path) -> String {
    let index_path = ir.join("index.json");
    let mut index = read_json(&index_path);
    let at = by_declarations(&index)[0];
    let file = index["modules"][at]["file"]
        .as_str()
        .expect("a file")
        .to_owned();
    let module_path = ir.join(&file);
    let mut module = read_json(&module_path);
    let last = module["declarations"]
        .as_array()
        .expect("declarations")
        .last()
        .expect("at least one declaration")["name"]
        .as_str()
        .expect("a name")
        .to_owned();
    let renamed = format!(
        "{}_renamed",
        module["declarations"][0]["name"].as_str().expect("a name")
    );
    module["declarations"][0]["name"] = json!(renamed);
    module["declarations"][0]["doc"] = json!(format!("mentions `Nat.find` and `{last}`"));
    write_json(&module_path, &module);

    let hash = index["modules"][at]["contentHash"]
        .as_str()
        .expect("a hash")
        .to_owned();
    index["modules"][at]["contentHash"] = json!(format!("0000{}", &hash[4..]));
    let module_name = index["modules"][at]["module"]
        .as_str()
        .expect("a name")
        .to_owned();
    write_json(&index_path, &index);
    module_name
}

/// State 4: `count` modules nobody imports disappear, files and index entries
/// both.
///
/// Leaves only, so that the tree stays consistent — `oracle.sh` says the same.
/// It takes both in one pass; this one takes them one at a time and recomputes,
/// because **the target package has exactly one module nobody imports**
/// 【実測: `InformationTheory`, the root that imports all 431 others】 and one
/// deletion does not distinguish "drop the entries that left" from "drop the
/// last entry".
fn mutate_removed(ir: &Path, count: usize) -> Vec<String> {
    let index_path = ir.join("index.json");
    let mut names = Vec::new();
    for _ in 0..count {
        let mut index = read_json(&index_path);
        let modules = index["modules"].as_array().expect("modules").clone();
        let own: BTreeSet<&str> = modules
            .iter()
            .map(|entry| entry["module"].as_str().expect("a name"))
            .collect();
        let mut imported: BTreeSet<String> = BTreeSet::new();
        for entry in &modules {
            let module = read_json(&ir.join(entry["file"].as_str().expect("a file")));
            for import in module["imports"].as_array().expect("imports") {
                let import = import.as_str().expect("a name");
                if own.contains(import) {
                    imported.insert(import.to_owned());
                }
            }
        }
        let Some(gone) = modules
            .iter()
            .find(|entry| !imported.contains(entry["module"].as_str().expect("a name")))
        else {
            break;
        };
        let name = gone["module"].as_str().expect("a name").to_owned();
        fs::remove_file(ir.join(gone["file"].as_str().expect("a file"))).expect("removable");
        index["modules"] = Value::Array(
            modules
                .iter()
                .filter(|entry| entry["module"].as_str() != Some(name.as_str()))
                .cloned()
                .collect(),
        );
        index["moduleCount"] = json!(index["modules"].as_array().expect("modules").len());
        write_json(&index_path, &index);
        names.push(name);
    }
    names
}

/// State 5: a module appears, with declarations no other module declares.
fn mutate_added(ir: &Path) -> String {
    let index_path = ir.join("index.json");
    let mut index = read_json(&index_path);
    let at = by_declarations(&index)[1];
    let source = index["modules"][at].clone();
    let mut module = read_json(&ir.join(source["file"].as_str().expect("a file")));
    let new = format!("{}Added", module["module"].as_str().expect("a name"));
    module["module"] = json!(new);
    for decl in module["declarations"].as_array_mut().expect("declarations") {
        decl["name"] = json!(format!("{}_added", decl["name"].as_str().expect("a name")));
    }
    module["imports"]
        .as_array_mut()
        .expect("imports")
        .push(source["module"].clone());
    let file = format!("modules/{new}.json");
    let body = serde_json::to_string(&module).expect("serialises");
    fs::write(ir.join(&file), &body).expect("writable");
    index["modules"]
        .as_array_mut()
        .expect("modules")
        .push(json!({
            "bytes": body.len(),
            "contentHash": "addedaddedadded1",
            "declarations": module["declarations"].as_array().expect("declarations").len(),
            "file": file,
            "module": new,
        }));
    index["moduleCount"] = json!(index["modules"].as_array().expect("modules").len());
    write_json(&index_path, &index);
    new
}

