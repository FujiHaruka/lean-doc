//! Milestone **M2-b**: the `contentHash` cache and the whole-package map delta.
//!
//! Two oracles, neither of which is this file's own opinion:
//!
//! - **`experiments/stage7h/oracle.sh`, transcribed.** Its contract is that a
//!   cached build equals a from-scratch build over *every* IR state, so both
//!   sides are run here over the same seven states — base / rerun / modified /
//!   removed / added / restored / stale-state — with one cache carried through,
//!   and all six artifacts compared byte for byte at each. The seventh state is
//!   the one that keeps plan §3's version-key discipline alive: a state file
//!   whose `derivation` was tampered with has to be dropped whole.
//! - **The frozen prototype's own answers**, for the two things a byte
//!   comparison of the six artifacts cannot see: the state file
//!   (`tests/data/…` has no copy — the real one is compared directly, see
//!   [`the_state_file_is_the_prototypes_bytes`]) and the delta
//!   (`tests/data/delta-expected.json`, generated by
//!   `tests/oracle/gen-delta-expected.ts` — **a frozen value**: the generator and
//!   the prototype it drove were removed with `experiments/` on 2026-08-16 and
//!   exist only at tag `experiments-frozen`, so HEAD cannot regenerate it).
//!
//! # Byte equality is not branch coverage (plan §7)
//!
//! Of the **35** [`BRANCHES`] this milestone added:
//!
//! | exercise | reaches |
//! |---|---:|
//! | the full-corpus six-file comparison (`tools/global-compare.sh` — M2-a's gate) | **5** |
//! | the seven states | **13** |
//! | everything real data can reach (seven states + the corpus delta) | **26** |
//! | curated cases only ([`NO_REAL_DATA_REACHES`]) | **9** |
//!
//! A run with no `--state` and no `--before` takes one path through all of
//! this, so the comparison M2-a was judged on cannot see 30 of the 35. The
//! dependency is asserted rather than commented:
//! [`the_curated_cases_cover_what_the_package_does_not`].

